def _sig_stars(pval: float) -> str:
    """Return significance asterisks for a p-value."""
    if np.isnan(pval):
        return ""
    if pval < 0.001:
        return "***"
    if pval < 0.01:
        return "**"
    if pval < 0.05:
        return "*"
    return "ns"


def compute_spearman(
    df: pd.DataFrame,
    error_col: str,
    covariate_list: list[tuple[str, str]],
) -> pd.DataFrame:
    """
    Compute Spearman ρ and two-sided p-value for each covariate vs *error_col*.

    Parameters
    ----------
    df             : merged flight-level DataFrame
    error_col      : "mae" or "mean_error"
    covariate_list : list of (column_name, label) tuples

    Returns
    -------
    DataFrame with columns: covariate, label, rho, pval, n, stars
    """
    rows = []
    for col, label in covariate_list:
        if col not in df.columns:
            print(f"  [skip] column '{col}' not found — check flight_covariates.csv")
            continue
        sub = df[[error_col, col]].dropna()
        n   = len(sub)
        if n >= 3:
            rho, pval = stats.spearmanr(sub[error_col], sub[col])
        else:
            rho, pval = np.nan, np.nan
        rows.append({
            "covariate": col,
            "label":     label,
            "rho":       rho,
            "pval":      pval,
            "n":         n,
            "stars":     _sig_stars(pval),
        })
        print(f"  {label:<42s}  ρ={rho:+.3f}  p={pval:.4e}  n={n}")
    return pd.DataFrame(rows)


