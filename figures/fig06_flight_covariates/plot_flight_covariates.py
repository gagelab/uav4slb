def plot_bar_chart(corr_df: pd.DataFrame, out_dir: Path, stem: str) -> None:
    """
    Horizontal bar chart of Spearman ρ (per-flight |MAE| vs each covariate).

    Bars are colored by sign of ρ; significance stars are annotated.

    Parameters
    ----------
    corr_df  : DataFrame from compute_spearman()
    out_dir  : output directory
    stem     : filename stem (e.g. "fig06_flight_covariates")
    """
    df = corr_df.dropna(subset=["rho", "pval"]).copy()
    df = df.sort_values("rho")          # ascending so strongest negative is bottom

    n_rows = len(df)
    fig, ax = plt.subplots(figsize=(10, 0.75 * n_rows + 1.8))

    colors = [BAR_COLOR_NEG if r < 0 else BAR_COLOR_POS for r in df["rho"]]
    ax.barh(range(n_rows), df["rho"], color=colors,
            edgecolor="black", linewidth=0.6, height=0.65)

    # Annotate each bar with ρ, significance stars, and n
    max_abs = df["rho"].abs().max() if len(df) else 0.3
    for i, (_, row) in enumerate(df.iterrows()):
        if np.isnan(row["rho"]):
            continue
        x_pos  = row["rho"] + (0.02 if row["rho"] >= 0 else -0.02)
        ha     = "left" if row["rho"] >= 0 else "right"
        label  = f"ρ = {row['rho']:+.3f} p = {row['pval']:.3f}"
        ax.text(x_pos, i, label, va="center", ha=ha, fontsize=9)

    ax.set_yticks(range(n_rows))
    ax.set_yticklabels(df["label"], fontsize=10)
    ax.axvline(0, color="black", linewidth=0.9, linestyle="--")
    ax.set_xlabel("Spearman ρ  (per-flight |MAE| vs flight conditions)", fontsize=11, fontweight="bold")
    ax.spines["left"].set_linewidth(1.5)
    ax.spines["bottom"].set_linewidth(1.5)

    # x-axis limits with enough margin for annotations
    margin = max_abs * 0.55
    ax.set_xlim(-(max_abs + margin), max_abs + margin)
    ax.xaxis.set_major_formatter(mticker.FormatStrFormatter("%.2f"))
    ax.grid(axis="x", alpha=0.3, linestyle="--")
    despine(ax)
    fig.tight_layout()
    save_fig(fig, out_dir, stem)


