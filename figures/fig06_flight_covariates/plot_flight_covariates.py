def plot_scatter_grid(
    df: pd.DataFrame,
    corr_df: pd.DataFrame,
    error_col: str,
    out_dir: Path,
    stem: str,
    covariate_list: list[tuple[str, str]],
) -> None:
    """
    Grid of scatter plots: per-flight error vs each covariate with OLS line.

    Parameters
    ----------
    df             : merged flight-level DataFrame
    corr_df        : Spearman correlation table from compute_spearman()
    error_col      : "mae" or "mean_error"
    out_dir        : output directory
    stem           : filename stem
    covariate_list : list of (column, label) tuples to plot
    """
    valid = [(col, lbl) for col, lbl in covariate_list if col in df.columns]
    if not valid:
        print("[scatter] no valid covariates — skipped")
        return

    corr_lookup = corr_df.set_index("covariate").to_dict("index") if len(corr_df) else {}

    n_cols = 3
    n_rows = int(np.ceil(len(valid) / n_cols))
    fig, axes = plt.subplots(n_rows, n_cols,
                             figsize=(5 * n_cols, 4 * n_rows),
                             squeeze=False)

    y_label = "|MAE| (per flight)" if error_col == "mae" else "Mean signed residual (per flight)"

    for idx, (col, label) in enumerate(valid):
        ax  = axes[idx // n_cols][idx % n_cols]
        sub = df[[error_col, col]].dropna()
        x, y = sub[col].values, sub[error_col].values

        ax.scatter(x, y, s=55, alpha=0.75, color="#3C6D56",
                   edgecolors="white", linewidths=0.4, zorder=3)

        # Horizontal reference at zero for signed error
        if error_col != "mae":
            ax.axhline(0, color="gray", linewidth=0.8, linestyle="--", zorder=2)

        # OLS trend line
        if len(x) >= 2:
            m, b = np.polyfit(x, y, 1)
            x_line = np.linspace(x.min(), x.max(), 200)
            ax.plot(x_line, m * x_line + b, color="#D29343",
                    linewidth=1.5, zorder=4)

        # Spearman ρ annotation
        if col in corr_lookup:
            r = corr_lookup[col]
            rho, pval, n = r["rho"], r["pval"], int(r["n"])
            if not np.isnan(rho):
                ann = f"ρ={rho:+.3f}  p={pval:.3f}  n={n}"
                ax.text(0.04, 0.96, ann, transform=ax.transAxes,
                        fontsize=8, va="top", ha="left",
                        bbox=dict(boxstyle="round,pad=0.3",
                                  fc="white", ec="lightgray", alpha=0.85))

        ax.set_xlabel(label, fontsize=9)
        ax.set_ylabel(y_label if idx % n_cols == 0 else "", fontsize=9)
        ax.grid(alpha=0.25, linestyle="--")
        despine(ax)

    # Hide unused subplot panels
    for idx in range(len(valid), n_rows * n_cols):
        axes[idx // n_cols][idx % n_cols].set_visible(False)

    fig.tight_layout()
    save_fig(fig, out_dir, stem)


