def _spearman_ci(rho: float, n: int, alpha: float = 0.05) -> tuple[float, float]:
    """
    95 % confidence interval for Spearman ρ via Fisher's z-transform.

    Returns (lower, upper).  Returns (nan, nan) when n < 4.
    """
    if np.isnan(rho) or n < 4:
        return np.nan, np.nan
    z     = np.arctanh(np.clip(rho, -0.9999, 0.9999))
    se    = 1.0 / np.sqrt(n - 3)
    z_crit = stats.norm.ppf(1 - alpha / 2)
    return float(np.tanh(z - z_crit * se)), float(np.tanh(z + z_crit * se))


def save_supplemental_table(
    corr_df: pd.DataFrame,
    merged_df: pd.DataFrame,
    out_dir: Path,
    stem: str = "tableS_flight_covariates",
    alpha: float = 0.05,
) -> None:
    """
    Build a full-precision supplemental table (CSV + styled PDF/PNG) summarising
    Spearman ρ, 95 % CI, p-value, covariate mean ± SD, and significance for
    the per-flight |MAE| analysis.

    Columns
    -------
    Covariate | Category | Spearman ρ | p-value | 95 % CI | Mean ± SD | Significant?

    Parameters
    ----------
    corr_df   : output of compute_spearman() for the |MAE| analysis
    merged_df : merged flight-level DataFrame (for mean/SD of each covariate)
    out_dir   : destination directory
    stem      : filename stem
    alpha     : significance threshold (default 0.05)
    """
    rows = []
    for _, r in corr_df.iterrows():
        col   = r["covariate"]
        rho   = r["rho"]
        pval  = r["pval"]
        n     = int(r["n"])
        lo, hi = _spearman_ci(rho, n, alpha=alpha)

        cov_vals = merged_df[col].dropna() if col in merged_df.columns else pd.Series([], dtype=float)
        mean_val = cov_vals.mean()
        sd_val   = cov_vals.std(ddof=1)

        rows.append({
            "Covariate":        r["label"],
            "Category":         COVARIATE_CATEGORIES.get(col, ""),
            "Spearman ρ":       rho,
            "p-value":          pval,
            "95 % CI":          f"[{lo:.3f}, {hi:.3f}]" if not np.isnan(lo) else "—",
            "Mean ± SD":        f"{mean_val:.2f} ± {sd_val:.2f}" if not np.isnan(mean_val) else "—",
            "Significant?":     "Yes" if (not np.isnan(pval) and pval < alpha) else "No",
            # keep full precision for the CSV
            "_rho_full":        rho,
            "_pval_full":       pval,
            "_ci_lo":           lo,
            "_ci_hi":           hi,
            "_mean":            mean_val,
            "_sd":              sd_val,
            "_n":               n,
        })

    tbl = pd.DataFrame(rows)

    # ── CSV (full precision) ─────────────────────────────────────────────────
    csv_cols = [
        "Covariate", "Category",
        "_rho_full", "_pval_full", "_ci_lo", "_ci_hi",
        "_mean", "_sd", "_n", "Significant?",
    ]
    csv_df = tbl[csv_cols].rename(columns={
        "_rho_full":  "Spearman_rho",
        "_pval_full": "p_value",
        "_ci_lo":     "CI_lower_95",
        "_ci_hi":     "CI_upper_95",
        "_mean":      "covariate_mean",
        "_sd":        "covariate_sd",
        "_n":         "n",
    })
    out_dir.mkdir(parents=True, exist_ok=True)
    csv_path = out_dir / f"{stem}.csv"
    csv_df.to_csv(csv_path, index=False, float_format="%.5f")
    print(f"[table] CSV saved → {csv_path}")

    # ── Styled matplotlib table ──────────────────────────────────────────────
    display_cols = ["Covariate", "Category", "Spearman ρ", "p-value",
                    "95 % CI", "Mean ± SD", "Significant?"]

    # Format numeric columns for display
    disp = tbl[display_cols].copy()
    disp["Spearman ρ"] = tbl["_rho_full"].map(
        lambda v: f"{v:+.3f}" if not np.isnan(v) else "—"
    )
    disp["p-value"] = tbl["_pval_full"].map(
        lambda v: f"{v:.4f}" if not np.isnan(v) else "—"
    )

    n_rows, n_cols = disp.shape
    col_widths = [0.26, 0.13, 0.10, 0.09, 0.14, 0.15, 0.10]  # relative widths
    fig_width  = 14
    fig_height = 0.55 * (n_rows + 1) + 0.8

    fig, ax = plt.subplots(figsize=(fig_width, fig_height))
    ax.set_axis_off()

    header_color = "#1C5A62"
    row_colors   = [["#f0f4f4" if i % 2 == 0 else "white"] * n_cols
                    for i in range(n_rows)]

    table = ax.table(
        cellText=disp.values,
        colLabels=display_cols,
        cellLoc="center",
        loc="center",
        colWidths=col_widths,
    )
    table.auto_set_font_size(False)
    table.set_fontsize(9)

    # Style header
    for j in range(n_cols):
        cell = table[0, j]
        cell.set_facecolor(header_color)
        cell.set_text_props(color="white", fontweight="bold")
        cell.set_edgecolor("white")
        cell.set_height(0.12)

    # Style data rows
    for i in range(n_rows):
        bg = "#f0f4f4" if i % 2 == 0 else "white"
        sig = disp.iloc[i]["Significant?"]
        for j in range(n_cols):
            cell = table[i + 1, j]
            cell.set_facecolor(bg)
            cell.set_edgecolor("#dddddd")
            cell.set_height(0.10)
            # Bold and slightly tinted for significant rows
            if sig == "Yes":
                cell.set_text_props(fontweight="bold")

    # Left-align the covariate and category columns
    for i in range(n_rows):
        table[i + 1, 0].get_text().set_ha("left")
        table[i + 1, 0].PAD = 0.02
        table[i + 1, 1].get_text().set_ha("left")

    ax.set_title(
        "Table S__ — Spearman correlations: per-flight |MAE| vs flight-level covariates\n"
        f"(EVA-02-B model, CV0; n = flights; α = {alpha})",
        fontsize=10, fontweight="bold", pad=12, loc="left",
    )

    fig.tight_layout()
    save_fig(fig, out_dir, stem)
    print(f"[table] figure saved → {out_dir / stem}")


