_FLIGHT_KEY_RE = re.compile(r"(\d{8})_([A-Za-z0-9]+)_")

def _extract_flight_key(filename: str) -> str | None:
    """
    Parse 'YYYYMMDD_FIELD' from an image filename.

    Filename convention: YYYYMMDD_FIELD_PLOTNUMBER.jpg
    Example: '20230713_G3_09565.jpg'  →  '20230713_G3'
    """
    m = _FLIGHT_KEY_RE.match(str(filename))
    return f"{m.group(1)}_{m.group(2).upper()}" if m else None


def compute_flight_mae(pred_path: Path) -> pd.DataFrame:
    """
    Aggregate per-image predictions to per-flight |MAE| and mean signed error.

    Parameters
    ----------
    pred_path : path to cv0_combined_predictions.csv

    Returns
    -------
    DataFrame with columns: flight_key, mae, mean_error
    """
    df = pd.read_csv(pred_path)
    df.columns = [c.strip().lower() for c in df.columns]

    # Compute signed_error if not already present
    if "signed_error" not in df.columns:
        df["signed_error"] = df["predicted"] - df["actual"]
    df["abs_error"] = df["signed_error"].abs()

    # Parse flight_key from image_filename
    df["flight_key"] = df["image_filename"].map(_extract_flight_key)
    df = df.dropna(subset=["flight_key"])

    # Aggregate to flight level
    flight_df = (
        df.groupby("flight_key")
        .agg(mae=("abs_error", "mean"), mean_error=("signed_error", "mean"))
        .reset_index()
    )
    print(f"[predictions] {len(flight_df)} flights  |  "
          f"MAE range {flight_df['mae'].min():.3f}–{flight_df['mae'].max():.3f}")
    return flight_df


def load_and_merge(pred_path: Path, cov_path: Path) -> pd.DataFrame:
    """
    Load and merge flight-level predictions with pre-computed covariates.

    The merge is performed on flight_key (YYYYMMDD_FIELD).  Rows without a
    matching covariate entry are retained but will have NaN for that covariate.

    Returns
    -------
    Merged DataFrame containing mae, mean_error, and all covariate columns.
    """
    flight_mae = compute_flight_mae(pred_path)

    cov = pd.read_csv(cov_path)
    cov.columns = [c.strip().lower() for c in cov.columns]
    print(f"[covariates] {len(cov)} flight rows loaded from {cov_path.name}")

    merged = flight_mae.merge(cov, on="flight_key", how="left")
    print(f"[merged]     {len(merged)} flights after join")
    return merged


