def main() -> None:
    parser = argparse.ArgumentParser(
        description="Figure 6 — Spearman correlations: flight-level |MAE| vs covariates.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--predictions", default=str(PREDICTIONS_DEFAULT),
                        help="Combined CV0 predictions CSV.")
    parser.add_argument("--covariates",  default=str(COVARIATES_DEFAULT),
                        help="Pre-joined flight covariate CSV.")
    parser.add_argument("--out_dir",     default=str(OUTPUT_DIR),
                        help="Output directory for figures and CSV.")
    args = parser.parse_args()

    pred_path = Path(args.predictions)
    cov_path  = Path(args.covariates)
    out_dir   = Path(args.out_dir)

    print("=" * 60)
    print("FIGURE 6 — FLIGHT COVARIATE × |MAE| CORRELATIONS")
    print("=" * 60)
    print(f"Predictions : {pred_path}")
    print(f"Covariates  : {cov_path}")
    print(f"Output      : {out_dir}\n")

    df = load_and_merge(pred_path, cov_path)

    # ── |MAE| analysis (primary figure) ─────────────────────────────────────
    print("\nSpearman ρ — |MAE| vs covariates")
    print("-" * 60)
    corr_mae = compute_spearman(df, "mae", COVARIATES_MAE)

    # ── Signed-error analysis (supplemental) ────────────────────────────────
    print("\nSpearman ρ — mean signed error vs covariates")
    print("-" * 60)
    corr_signed = compute_spearman(df, "mean_error", COVARIATES_SIGNED)

    # ── Save statistics table ────────────────────────────────────────────────
    corr_all = pd.concat(
        [corr_mae.assign(error_type="mae"),
         corr_signed.assign(error_type="mean_error")],
        ignore_index=True,
    )
    csv_path = out_dir / "fig06_flight_covariates_stats.csv"
    out_dir.mkdir(parents=True, exist_ok=True)
    corr_all.to_csv(csv_path, index=False, float_format="%.6f")
    print(f"\n[stats] saved → {csv_path}")

    # ── Figures ──────────────────────────────────────────────────────────────
    print("\nBuilding Figure 6 (|MAE| bar chart) …")
    plot_bar_chart(corr_mae, out_dir, "fig06_flight_covariates")

    print("\nBuilding supplemental scatter grid (|MAE|) …")
    plot_scatter_grid(df, corr_mae, "mae", out_dir,
                      "fig06_flight_covariates_scatter_mae", COVARIATES_MAE)

    print("\nBuilding supplemental scatter grid (signed error) …")
    plot_scatter_grid(df, corr_signed, "mean_error", out_dir,
                      "fig06_flight_covariates_scatter_signed", COVARIATES_SIGNED)

    print("\nBuilding supplemental statistics table …")
    save_supplemental_table(corr_mae, df, out_dir,
                            stem="tableS_flight_covariates")

    print("\nDone.")


if __name__ == "__main__":
    main()
